#!/bin/bash
# Write the AUR's PKGBUILD, and the install file it names, into DIR. It's this
# checkout's PKGBUILD changed to build the release tagged v<pkgver> instead of
# the files beside it. The release tarball's checksum is left SKIP, for
# updpkgsums to fill in once the tag exists (tools/aur-publish.sh).
#
#   tools/aur-pkgbuild.sh DIR
set -eu

ROOT=$(cd "$(dirname "$0")/.." && pwd)
OUT=${1:?usage: tools/aur-pkgbuild.sh DIR}
VERSION=$(sed -n 's/^pkgver=//p' "$ROOT/PKGBUILD")
mkdir -p "$OUT"

# Each change has to apply, so a PKGBUILD edit that sidesteps one fails here
# rather than publishing something half converted.
awk -v ver="$VERSION" '
  /^# Build this checkout:/ {
    print "# Generated by tools/aur-pkgbuild.sh from the PKGBUILD of"
    print "# https://github.com/t4t5/omdrop-owl at v" ver ": change it there."
    header++; skip = 1; next
  }
  skip && /^pkgname=/ { skip = 0 }
  skip { next }
  sub(/^source=\(/, "source=(\"${pkgname}-${pkgver}.tar.gz::${url}/archive/refs/tags/v${pkgver}.tar.gz\"\n        ") { source++ }
  sub(/^sha256sums=\(/, "sha256sums=(\047SKIP\047 ") { sums++ }
  gsub(/local tree="\$\{startdir\}"/, "local tree=\"${srcdir}/${pkgname}-${pkgver}\"") { tree++ }
  { print }
  END { exit !(header == 1 && source == 1 && sums == 1 && tree >= 1) }
' "$ROOT/PKGBUILD" > "$OUT/PKGBUILD" \
  || { echo "tools/aur-pkgbuild.sh: PKGBUILD no longer has the shape this expects" >&2; exit 1; }
if grep -n startdir "$OUT/PKGBUILD" >&2; then
  echo "tools/aur-pkgbuild.sh: the AUR's PKGBUILD can't use \${startdir}: use \${tree}" >&2
  exit 1
fi
cp "$ROOT/omdrop-owl.install" "$OUT/"
